//! Verified celestial catalog spanning the Sun, major planets, Pluto, priority ocean/icy moons,
//! asteroids/dwarf planets, nearby exoplanets, and deep-sky nebulae.
//! Every numerical parameter and fact string is grounded in official NASA NSSDCA, JPL SSD/SBDB,
//! NASA Exoplanet Archive, and Hubble/Webb Science releases.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum BodyCategory {
    Star,
    Planet,
    DwarfPlanet,
    Moon,
    Asteroid,
    Comet,
    LagrangePoint,
    Exoplanet,
    Nebula,
}

impl BodyCategory {
    pub fn label(self) -> &'static str {
        match self {
            Self::Star => "Star",
            Self::Planet => "Planet",
            Self::DwarfPlanet => "Dwarf Planet",
            Self::Moon => "Moon",
            Self::Asteroid => "Near-Earth / Main-Belt Asteroid",
            Self::Comet => "Eccentric Comet",
            Self::LagrangePoint => "Sun-Earth Lagrange Point",
            Self::Exoplanet => "Exoplanet",
            Self::Nebula => "Deep-Sky Nebula",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ScanBand {
    OpticalNir,
    RadarGravity,
    MagnetometerPlasma,
    ThermalMassSpec,
    HighEnergyUvXray,
}

impl ScanBand {
    pub const ALL: [ScanBand; 5] = [
        ScanBand::OpticalNir,
        ScanBand::RadarGravity,
        ScanBand::MagnetometerPlasma,
        ScanBand::ThermalMassSpec,
        ScanBand::HighEnergyUvXray,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Self::OpticalNir => "OPTICAL_NIR",
            Self::RadarGravity => "RADAR_GRAV",
            Self::MagnetometerPlasma => "MAG_PLASMA",
            Self::ThermalMassSpec => "THERMAL_MS",
            Self::HighEnergyUvXray => "UV_XRAY",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Self::OpticalNir => "Optical / NIR Imaging Spectrometer",
            Self::RadarGravity => "Radar Altimeter & Gravity Gradiometer",
            Self::MagnetometerPlasma => "Fluxgate Magnetometer & Plasma Wave",
            Self::ThermalMassSpec => "Thermal IR & Mass Spectrometer",
            Self::HighEnergyUvXray => "High-Energy UV / X-Ray Sensor",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BandFinding {
    pub band: ScanBand,
    pub headline: String,
    pub detail: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CelestialBody {
    pub id: String,
    pub name: String,
    pub designation: String,
    pub category: BodyCategory,
    /// Optional parent body ID for natural satellites (e.g. `"earth"`, `"jupiter"`, `"saturn"`).
    pub parent_id: Option<String>,
    /// Semi-major axis in AU (for moons: parent-centric semi-major axis in AU; for nebulae/exoplanets: system/visual placement).
    pub semi_major_axis_au: f64,
    pub eccentricity: f64,
    pub inclination_deg: f64,
    pub lon_ascending_node_deg: f64,
    pub arg_periapsis_deg: f64,
    pub mean_anomaly_j2000_deg: f64,
    /// Sidereal orbital period in Earth days (`0.0` for Sun or stationary deep-sky nebulae).
    pub orbital_period_days: f64,
    /// Distance from Earth/Sun in light-years for interstellar targets (`0.0` for Solar System bodies).
    pub distance_ly: f64,
    /// Physical volumetric/equatorial radius in km (or characteristic half-span in km for nebulae if applicable).
    pub radius_km: f64,
    /// Span in light-years for extended nebulae (`0.0` for compact bodies).
    pub span_ly: f64,
    /// Mass in units of `10^24 kg` (`0.0` if unmeasured/extended nebula).
    pub mass_10e24_kg: f64,
    /// Mean bulk density in `kg/m^3` (`0.0` if diffuse).
    pub density_kg_m3: f64,
    /// Mean surface gravity in `m/s^2`.
    pub gravity_m_s2: f64,
    /// Escape velocity in `km/s`.
    pub escape_velocity_km_s: f64,
    /// Mean temperature in Celsius.
    pub mean_temp_c: f64,
    /// RGB color `[0.0..=1.0]` for 3D rendering.
    pub color_rgb: [f32; 3],
    pub has_rings: bool,
    pub has_global_mag_field: bool,
    pub known_moons: u32,
    /// Canonical public source URL verifying all metrics and findings.
    pub source_url: String,
    pub source_title: String,
    /// Whether this body was dynamically imported from a live public astronomy API.
    pub imported_from_api: bool,
    pub findings: Vec<BandFinding>,
}

impl CelestialBody {
    pub fn finding_for(&self, band: ScanBand) -> Option<&BandFinding> {
        self.findings.iter().find(|f| f.band == band)
    }

    /// Standard gravitational parameter `GM` in `km^3 / s^2`.
    /// Uses CODATA `G = 6.67430e-20 km^3 / (kg * s^2)`.
    pub fn gm_km3_s2(&self) -> f64 {
        if self.mass_10e24_kg > 0.0 {
            self.mass_10e24_kg * 1.0e24 * 6.67430e-20
        } else {
            // Nominal station-keeping micro-gravity parameter for small asteroids or nebula halo stations
            0.05
        }
    }
}

